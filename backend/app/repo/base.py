"""What the business logic needs from storage.

Two implementations: `SupabaseRepo` (production, Row Level Security applies
because every call runs with the user's own token) and `MemoryRepo`
(tests and local development without an account).
"""
from __future__ import annotations

from datetime import date
from typing import Any, Protocol, Sequence

from app.schemas import RecipeIn


class Repo(Protocol):
    def get_profile(self, user_id: str) -> dict[str, Any] | None: ...
    def count_own_recipes(self, user_id: str) -> int: ...
    def recipe_name_exists(self, user_id: str, name: str) -> bool: ...
    def create_recipe(self, user_id: str, data: RecipeIn) -> dict[str, Any]: ...
    def get_recipe(self, user_id: str, recipe_id: str) -> dict[str, Any] | None: ...
    def list_visible_recipes(self, user_id: str) -> list[dict[str, Any]]: ...
    def delete_recipe(self, user_id: str, recipe_id: str) -> None: ...
    def list_photos(self, recipe_id: str) -> list[dict[str, Any]]: ...
    def add_photo(self, recipe_id: str, position: int, path: str) -> None: ...
    def delete_photo(self, recipe_id: str, position: int) -> None: ...
    def save_week_plan(self, user_id: str, week: date, recipe_ids: Sequence[str | None]) -> str: ...
    def follow(self, follower_id: str, followee_id: str) -> None: ...
    def unfollow(self, follower_id: str, followee_id: str) -> None: ...


class PhotoStorage(Protocol):
    def upload(self, path: str, data: bytes, content_type: str) -> None: ...
    def remove(self, paths: Sequence[str]) -> None: ...
    def public_url(self, path: str) -> str: ...


def cost_per_serving(ingredients: Sequence[dict[str, Any]]) -> float | None:
    """Built-in recipes carry prices; user recipes usually don't (None = unknown)."""
    prices = [i.get("price_per_unit") for i in ingredients]
    if not ingredients or all(p is None for p in prices):
        return None
    total = sum(float(i["qty"]) * float(i.get("price_per_unit") or 0) for i in ingredients)
    return round(total / 4, 2)  # recipes are written for 4 people
